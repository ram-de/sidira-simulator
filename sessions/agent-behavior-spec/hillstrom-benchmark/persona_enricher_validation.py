"""Step 1: persona-conditioning enrichment + validation (#342).

The production Hillstrom personas carry segment signal only as raw-stat jargon
("value_sensitivity.history (-0.60σ)"), with empty snapshots and ungenerated jtbd —
the cluster-naming step ("LLM naming unavailable") never ran. The heterogeneity run
showed the comparative pass recovers the who-responds-more ranking GIVEN readable
segment descriptions. This validates the missing piece: an enricher that turns a
segment's REAL feature statistics into a rich natural-language description, and
checks that ENRICHER-GENERATED descriptions (not hand-written) recover heterogeneity
through the production comparative pass.

38 gender×recency×channel strata; per-stratum feature profile computed from the RCT
CSV; description generated by the enricher; scored Spearman(predicted delta, real
uplift). CERTIFIED iff ρ>0.30 AND perm p<0.05 (same bar as the hand-written run, ρ+0.385).

    PYTHONPATH=backend <venv>/bin/python <thisfile> [--k 4] [--smoke]
"""
