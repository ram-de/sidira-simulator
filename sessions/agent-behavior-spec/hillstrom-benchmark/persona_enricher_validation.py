CSV = "/Users/ram/Projects/sidira-simulator/local-artifacts/hillstrom/hillstrom.csv"
EMAILS = ["Mens E-Mail", "Womens E-Mail"]
_OBJ = re.compile(r"\{[^{}]*\}")


def gender_of(r):
    m, w = int(r["mens"]), int(r["womens"])
    return "mens_buyer" if (m and not w) else "womens_buyer" if (w and not m) else "both_buyer" if (m and w) else None


def rec_of(r):
    v = float(r["recency"]); return "recent" if v <= 3 else "lapsing" if v <= 6 else "dormant"


def feature_profiles(csv_path):
    """Per (gender,recency,channel) stratum: REAL averaged feature stats (the kind a
    cluster centroid carries), computed from the raw RCT rows."""
    rows = list(csv.DictReader(open(csv_path)))
    agg = defaultdict(lambda: {"n": 0, "mens": 0, "womens": 0, "recency": 0.0,
                               "history": 0.0, "newbie": 0, "zip": defaultdict(int)})
    for r in rows:
        g = gender_of(r)
        if g is None:
            continue
        a = agg[(g, rec_of(r), r["channel"])]
        a["n"] += 1; a["mens"] += int(r["mens"]); a["womens"] += int(r["womens"])
        a["recency"] += float(r["recency"]); a["history"] += float(r["history"])
        a["newbie"] += int(r["newbie"]); a["zip"][r["zip_code"]] += 1
    out = {}
    for key, a in agg.items():
        n = a["n"]
        out[key] = {
            "n": n,
            "bought_mens_pct": round(100 * a["mens"] / n),
            "bought_womens_pct": round(100 * a["womens"] / n),
            "avg_months_since_purchase": round(a["recency"] / n, 1),
            "avg_prior_spend_usd": round(a["history"] / n),
            "new_customer_pct": round(100 * a["newbie"] / n),
            "top_location": max(a["zip"].items(), key=lambda kv: kv[1])[0],
        }
    return out


def enrich_description(client, profile: dict) -> str:
    """The missing cluster-naming step: real feature stats -> rich NL audience description."""
    msgs = [
        {"role": "system", "content": "You write concise, plain-language audience descriptions "
         "for a marketing analyst, from segment statistics. No jargon, no stat notation — just "
         "who these customers are in 1-2 sentences a human can reason about."},
        {"role": "user", "content":
            "Segment statistics:\n" + json.dumps(profile, indent=2) +
            "\n\nWrite a 1-2 sentence description of who these customers are (purchase history, "
            "recency, spend, tenure). Output only the description."}]
    return client.chat(msgs, max_tokens=160, temperature=0.0).strip()


def engine_case(rows, email):
    c = build_hillstrom_case(rows, arm=email, metric_name="visit")
    data = c.hypothesis.model_dump()
    data.update({"metric_name": "visit", "decision_point": "the customer is looking at their inbox"})
    return c.capability, Hypothesis.model_validate(data)


def cell_delta(client, persona, cap, hyp, k):
    ds = []
    for i in range(k):
        sysp = compose_comparative_metric_prompt(customer_id="hillstrom", persona=persona,
                                                 capability=cap, hypothesis=hyp, sample_index=i)
        try:
            ds.append(elicit_visit_delta(client, system_prompt=sysp, capability_name=cap.name,
                                         decision_point=hyp.decision_point or "", temperature=0.5, seed=5000 + i))
        except ValueError:
            continue
    return statistics.mean(ds) if ds else None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--k", type=int, default=4)
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    cells = FH.build_cases(CSV)
    profiles = feature_profiles(CSV)
    rows, _ = load_hillstrom_csv(CSV)
    caps = {e: engine_case(rows, e) for e in EMAILS}
    client = get_chat_client("claude-sonnet-4-6")
    if args.smoke:
        cells = cells[:2]

    # Enrich each stratum's description ONCE from its real feature profile.
    desc_cache = {}
    for c in cells:
        key = (c["gender"], c["recency"], c["channel"])
        if key not in desc_cache:
            desc_cache[key] = enrich_description(client, profiles[key])
    if args.smoke:
        k0 = (cells[0]["gender"], cells[0]["recency"], cells[0]["channel"])
        print("SAMPLE enriched description:\n ", desc_cache[k0], "\n")

    preds, reals, dropped = [], [], 0
    for n, c in enumerate(cells):
        key = (c["gender"], c["recency"], c["channel"])
        persona = Persona(id="|".join(key), name=" / ".join(key), description=desc_cache[key])
        cap, hyp = caps[c["email"]]
        d = cell_delta(client, persona, cap, hyp, args.k)
        if d is None:
            dropped += 1; continue
        preds.append(d); reals.append(c["real_visit"])
        if (n + 1) % 10 == 0:
            print(f"  ...{n+1}/{len(cells)}", flush=True)
    rho = spearman_rho(preds, reals); tau = kendall_tau_b(preds, reals); p = FH.perm_p(preds, reals, rho)
    dir_acc = sum(_sign_dead(a, 0) == _sign_dead(b, 0) for a, b in zip(preds, reals)) / len(preds)
    print(f"\n=== ENRICHER-GENERATED descriptions through the comparative engine (n={len(preds)}, dropped={dropped}) ===")
    print(f"  Spearman rho = {rho:+.3f}  (perm p = {p:.4f})   Kendall tau_b = {tau:+.3f}   dir_acc = {dir_acc:.3f}")
    print(f"  bar (rho>0.30 AND p<0.05): {'CERTIFIED' if (rho > 0.30 and p < 0.05) else 'NOT certified'}")
    print(f"  baselines: hand-written rich personas ρ +0.385 | raw-jargon GMM personas: clustered/no heterogeneity")
    if not args.smoke:
        HERE.joinpath("persona_enricher_result.json").write_text(json.dumps(
            {"n": len(preds), "dropped": dropped, "spearman": rho, "kendall": tau,
             "perm_p": p, "direction_accuracy": dir_acc, "k": args.k,
             "sample_enriched_descriptions": {f"{k[0]}/{k[1]}/{k[2]}": v for k, v in list(desc_cache.items())[:4]}},
            indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
